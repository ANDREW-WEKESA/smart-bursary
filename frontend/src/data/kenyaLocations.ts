// Get all counties
export const getCounties = (): string[] => {
  return Object.keys(kenyaLocations).sort();
};

// Get sub-counties for a county
export const getSubCounties = (county: string): string[] => {
  if (!county || !kenyaLocations[county as keyof typeof kenyaLocations]) return [];
  return Object.keys(kenyaLocations[county as keyof typeof kenyaLocations].subCounties).sort();
};

// Get wards for a sub-county
export const getWards = (county: string, subCounty: string): string[] => {
  if (!county || !subCounty) return [];
  const countyData = kenyaLocations[county as keyof typeof kenyaLocations];
  if (!countyData) return [];
  const wards = countyData.subCounties[subCounty as keyof typeof countyData.subCounties];
  return wards ? wards.sort() : [];
};
